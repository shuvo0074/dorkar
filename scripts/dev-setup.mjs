// One-time (and idempotent) local setup without Docker:
//   pnpm dev:setup            → .env.dev, database, per-service schemas/roles, all migrations
// Uses DATABASE_URL (admin connection, default postgres://localhost:5432/dorkar) and REDIS_URL.
import { execFileSync, spawnSync } from 'node:child_process';
import { generateKeyPairSync, randomBytes } from 'node:crypto';
import { appendFileSync, existsSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import pg from './pg-shim.mjs';
import { DEV_ENV_FILE, readDevEnv, ROOT, SERVICES, serviceEnv } from './backend-services.mjs';

const hex = (n) => randomBytes(n).toString('hex');

if (!existsSync(DEV_ENV_FILE)) {
  const { privateKey } = generateKeyPairSync('ed25519');
  const pem = privateKey.export({ type: 'pkcs8', format: 'pem' }).toString();
  const lines = [
    '# Local development secrets — generated by scripts/dev-setup.mjs, never commit.',
    `DATABASE_URL=${process.env.DATABASE_URL ?? 'postgres://localhost:5432/dorkar'}`,
    `REDIS_URL=${process.env.REDIS_URL ?? 'redis://localhost:6379/0'}`,
    'LOG_LEVEL=info',
    `INTERNAL_API_TOKEN=${hex(32)}`,
    `PII_HASH_KEY=${hex(32)}`,
    `MEDIA_SIGNING_KEY=${hex(32)}`,
    `OTP_PEPPER=${hex(32)}`,
    `JWT_KEY_ID=dev-${hex(3)}`,
    `JWT_PRIVATE_KEY=${Buffer.from(pem).toString('base64')}`,
  ];
  writeFileSync(DEV_ENV_FILE, `${lines.join('\n')}\n`, { mode: 0o600 });
  console.log('created .env.dev');
}
// Secrets added after a developer's .env.dev was created are appended, never regenerated.
if (!/^METRICS_TOKEN=/m.test(readFileSync(DEV_ENV_FILE, 'utf8'))) {
  appendFileSync(DEV_ENV_FILE, `METRICS_TOKEN=${hex(32)}\n`);
  console.log('added METRICS_TOKEN to .env.dev');
}
const dev = readDevEnv();

// 1. database
const admin = new URL(dev.DATABASE_URL);
const dbName = admin.pathname.slice(1);
admin.pathname = '/postgres';
const client = new pg.Client({ connectionString: admin.toString() });
await client.connect();
const exists = await client.query('select 1 from pg_database where datname = $1', [dbName]);
if (!exists.rowCount) {
  await client.query(`create database "${dbName.replace(/"/g, '')}"`);
  console.log(`created database ${dbName}`);
}
await client.end();

// 2. schemas + least-privilege roles (same script production uses)
execFileSync(resolve(ROOT, 'infra/docker/postgres/init.sh'), {
  env: { ...process.env, PGURL: dev.DATABASE_URL },
  stdio: 'inherit',
});

// 3. migrations, each as its own service role
for (const name of Object.keys(SERVICES)) {
  const s = SERVICES[name];
  const r = spawnSync('npx', ['tsx', 'src/cli/migrate.ts', 'up'], {
    cwd: resolve(ROOT, s.dir),
    env: { ...process.env, ...serviceEnv(name, dev), LOG_LEVEL: 'warn' },
    stdio: 'inherit',
  });
  if (r.status !== 0) {
    console.error(`migrations failed for ${name}`);
    process.exit(1);
  }
  console.log(`✔ ${name} migrated`);
}
console.log('\nReady. Start everything with: pnpm dev:backend');
