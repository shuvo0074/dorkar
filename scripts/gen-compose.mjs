// Generates infra/docker/compose.yml from scripts/backend-services.mjs so local Docker and the
// non-Docker dev runner never drift.   node scripts/gen-compose.mjs
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { GATEWAY_PORT, ROOT, SERVICES } from './backend-services.mjs';

const svcUrl = (name) => `http://${name}:${SERVICES[name].port}`;
const lines = [];
const w = (s = '') => lines.push(s);

w('# GENERATED by scripts/gen-compose.mjs — edit that script, not this file.');
w(
  '# Local full stack:  cp infra/docker/secrets.env.example infra/docker/secrets.env  (fill it in)',
);
w('#                    docker compose -f infra/docker/compose.yml up --build');
w('# Containers run their migrations on start for convenience; production runs them as a separate');
w('# job before traffic (docs/architecture/02-data.md §4).');
w('name: dorkar');
w();
w('x-node: &node');
w('  restart: unless-stopped');
w('  env_file: [secrets.env]');
w('  depends_on:');
w('    postgres: { condition: service_healthy }');
w('    redis: { condition: service_healthy }');
w();
w('x-env: &env');
w('  NODE_ENV: development');
w('  HOST: 0.0.0.0');
w('  LOG_LEVEL: info');
w('  REDIS_URL: redis://redis:6379/0');
w('  DATABASE_SSL: disable');
w("  TRUST_PROXY: '1'");
w(`  JWKS_URL: ${svcUrl('identity')}/.well-known/jwks.json`);
w(`  VERIFICATION_URL: ${svcUrl('verification')}`);
w(`  PROFILE_URL: ${svcUrl('profile')}`);
w(`  IDENTITY_URL: ${svcUrl('identity')}`);
w(`  MEDIA_URL: ${svcUrl('media')}`);
w();
w('services:');
w('  postgres:');
w('    image: postgres:17-alpine');
w('    environment: { POSTGRES_USER: postgres, POSTGRES_PASSWORD: postgres, POSTGRES_DB: dorkar }');
w("    ports: ['127.0.0.1:5433:5432']");
w('    volumes:');
w('      - pgdata:/var/lib/postgresql/data');
w('      - ./postgres/init.sh:/docker-entrypoint-initdb.d/10-init.sh:ro');
w('    healthcheck:');
w("      test: ['CMD-SHELL', 'pg_isready -U postgres -d dorkar']");
w('      interval: 5s');
w('      retries: 10');
w();
w('  redis:');
w('    image: redis:7-alpine');
w(
  "    command: ['redis-server', '--save', '', '--appendonly', 'no', '--maxmemory', '256mb', '--maxmemory-policy', 'noeviction']",
);
w("    ports: ['127.0.0.1:6380:6379']");
w('    healthcheck:');
w("      test: ['CMD', 'redis-cli', 'ping']");
w('      interval: 5s');
w('      retries: 10');

for (const [name, s] of Object.entries(SERVICES)) {
  const pkg = `@dorkar/${s.dir.split('/')[1]}`;
  w();
  w(`  ${name}:`);
  w('    <<: *node');
  w('    build:');
  w('      context: ../..');
  w('      dockerfile: infra/docker/service.Dockerfile');
  w(`      args: { SERVICE: ${s.dir.split('/')[1]}, PACKAGE: '${pkg}' }`);
  w(
    `    command: ['sh', '-c', 'node dist/migrate.js up && exec node --enable-source-maps dist/main.js']`,
  );
  w('    environment:');
  w('      <<: *env');
  w(`      SERVICE_NAME: ${name}-service`);
  w(`      PORT: '${s.port}'`);
  w(`      DATABASE_URL: postgres://svc_${s.schema}:dev_${s.schema}_pw@postgres:5432/dorkar`);
  w(`      DATABASE_SCHEMA: ${s.schema}`);
  if (name === 'identity') {
    w('      CORS_ORIGINS: http://localhost:5173');
    w('      SMS_PROVIDER: file');
    w('      SMS_FILE_PATH: /tmp/dev-sms.log');
    w("      REFRESH_COOKIE_SECURE: 'false'");
  }
  if (name === 'media') {
    w('      MEDIA_STORAGE: local');
    w('      MEDIA_LOCAL_DIR: /app/var/media');
    w(`      MEDIA_PUBLIC_BASE_URL: http://localhost:${GATEWAY_PORT}`);
  }
  if (name === 'notification') {
    w('      SMS_PROVIDER: file');
    w('      SMS_FILE_PATH: /tmp/notification-sms.log');
    w('      PUSH_PROVIDER: file');
    w('      PUSH_FILE_PATH: /tmp/notification-push.log');
  }
  w(`    expose: ['${s.port}']`);
}

w();
w('  gateway:');
w('    <<: *node');
w('    build:');
w('      context: ../..');
w('      dockerfile: infra/docker/service.Dockerfile');
w("      args: { SERVICE: gateway, PACKAGE: '@dorkar/gateway' }");
w('    environment:');
w('      NODE_ENV: development');
w('      HOST: 0.0.0.0');
w(`      PORT: '${GATEWAY_PORT}'`);
w('      LOG_LEVEL: info');
w('      REDIS_URL: redis://redis:6379/0');
w('      CORS_ORIGINS: http://localhost:5173');
w("      TRUST_PROXY: '1'");
for (const name of Object.keys(SERVICES))
  w(`      UPSTREAM_${name.toUpperCase()}_URL: ${svcUrl(name)}`);
w(`    ports: ['127.0.0.1:${GATEWAY_PORT}:${GATEWAY_PORT}']`);
w();
w('volumes:');
w('  pgdata:');

writeFileSync(resolve(ROOT, 'infra/docker/compose.yml'), `${lines.join('\n')}\n`);
console.log('wrote infra/docker/compose.yml');
