// Generates src/ui/icons.tsx from the web app's SVG icon set, so both platforms draw the same icons.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
const here = dirname(fileURLToPath(import.meta.url));
const web = join(here, '../../web/src/components');
const elements = { path: 'Path', circle: 'Circle', rect: 'Rect', line: 'Line', ellipse: 'Ellipse', polyline: 'Polyline', polygon: 'Polygon', g: 'G' };
const seen = new Set();
const out = [];
// The web's 48-unit item glyphs are not ported: the app draws kinds with these 24-unit icons.
for (const file of ['icons/icons.tsx']) {
  const src = readFileSync(join(web, file), 'utf8');
  for (const m of src.matchAll(/export const (\w+) = \(\) => \(\n([\s\S]*?)\n\);/g)) {
    const [, name, body] = m;
    if (seen.has(name) || /Glyph$/.test(name)) continue;
    seen.add(name);
    const inner = body
      .replace(/<\/?(Icon|svg)\b[^>]*>/g, '')
      .replace(/<(\/?)(path|circle|rect|line|ellipse|polyline|polygon|g)\b/g, (_, s, e) => `<${s}${elements[e]}`)
      .replace(/className="[^"]*"/g, '')
      .trim();
    if (!inner) continue;
    out.push(`export const ${name} = (p: IconProps) => (\n  <Icon {...p}>\n    ${inner}\n  </Icon>\n);`);
  }
}
const native = {
  AlertIcon: '<Path d="M12 3 22 20H2z" /><Path d="M12 9.5v5" /><Circle cx="12" cy="17.2" r="0.6" />',
  NoteIcon: '<Circle cx="12" cy="12" r="9" /><Path d="M12 11v6" /><Circle cx="12" cy="7.5" r="0.6" />',
  CheckIcon: '<Path d="m5 12.5 4.5 4.5L19 7.5" />',
  ChevronIcon: '<Path d="m9 6 6 6-6 6" />',
  BackIcon: '<Path d="m15 6-6 6 6 6" />',
  CloseIcon: '<Path d="M6 6l12 12M18 6 6 18" />',
  CameraIcon: '<Path d="M4 8h3l2-3h6l2 3h3a1 1 0 0 1 1 1v10a1 1 0 0 1-1 1H4a1 1 0 0 1-1-1V9a1 1 0 0 1 1-1z" /><Circle cx="12" cy="13" r="3.5" />',
  KeyIcon: '<Circle cx="8" cy="15" r="4" /><Path d="m11 12 8-8M16 7l3 3" />',
  SendIcon: '<Path d="M4 12 20 4l-4 16-4-7z" /><Path d="m12 13 8-9" />',
};
for (const [name, inner] of Object.entries(native)) {
  out.push(`export const ${name} = (p: IconProps) => (\n  <Icon {...p}>\n    ${inner}\n  </Icon>\n);`);
}
writeFileSync(join(here, '../src/ui/icons.tsx'), `// Generated by scripts/gen-icons.mjs from the web icon set. Do not edit by hand.
import type { ReactNode } from 'react';
import Svg, { Circle, Ellipse, G, Line, Path, Polygon, Polyline, Rect } from 'react-native-svg';
import { c } from '../design/tokens';

export interface IconProps { color?: string; size?: number; strokeWidth?: number }

function Icon({ color = c.ink, size = 24, strokeWidth = 2, children }: IconProps & { children: ReactNode }) {
  return (
    <Svg width={size} height={size} viewBox="0 0 24 24" fill="none" stroke={color} strokeWidth={strokeWidth} strokeLinecap="round" strokeLinejoin="round">
      {children}
    </Svg>
  );
}
// Keep every drawing element referenced even if an icon set stops using one.
void [Circle, Ellipse, G, Line, Path, Polygon, Polyline, Rect];

${out.join('\n\n')}
`);
console.log(`${out.length} icons`);
